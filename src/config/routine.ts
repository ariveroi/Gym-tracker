export function targetLabel(e: ExerciseDefinition) {
  return `${e.minReps}${e.maxReps !== e.minReps ? `–${e.maxReps}` : ''} ${e.targetUnit === 'seconds' ? 's' : 'reps'}${e.unilateral ? ' / lado' : ''}`;
}
