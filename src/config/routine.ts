import type {
  ExerciseDefinition,
  WorkoutDay,
  WorkoutDayId,
} from '@/types/workout';
function exercise(
  id: string,
  name: string,
  sets: number,
  minReps: number,
  maxReps: number,
  restSeconds: number,
  instructions: string,
  options: Partial<ExerciseDefinition> = {},
): ExerciseDefinition {
  return {
    id,
    name,
    sets,
    minReps,
    maxReps,
    restSeconds,
    instructions,
    targetUnit: 'reps',
    unilateral: false,
    rir: 3,
    videoUrl: null,
    trackOneRM: true,
    ...options,
  };
}
